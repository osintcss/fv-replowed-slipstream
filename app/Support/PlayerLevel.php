    public static function fromXp(int $xp): int
    {
        $xp = max(0, $xp);

        for ($level = 100; $level >= 1; $level--) {
            if ($xp >= self::XP_THRESHOLDS[$level]) {
                if ($xp < 1500000) {
                    return $level;
                }

                return 100 + (int) floor(($xp - 1500000) / 100000) + 1;
            }
        }

        return 1;
    }
